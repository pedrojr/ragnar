def test_acl_resolution():
    acl = Acl.from_json(json.dumps({"clients": [
        {"name": "a", "token_sha256": hash_token("t1"), "repos": ["myapp"]},
        {"name": "adm", "token_sha256": hash_token("t2"), "repos": ["*"]},
    ]}))
    assert acl.client_for(None) is None and acl.client_for("Bearer nope") is None
    a = acl.client_for("Bearer t1")
    assert a.resolve(None) == ["myapp"] and a.resolve("myapp") == ["myapp"]
    with pytest.raises(RagnarError):
        a.resolve("other")
    assert acl.client_for("bearer t2").resolve(None) is None


def test_acl_repos_must_be_a_list(tmp_path):
    # a string would become its characters: "a*" would grant every repository through its "*"
    path = tmp_path / "acl.json"
    path.write_text(json.dumps({"clients": [{"name": "a", "token_sha256": hash_token("t"), "repos": "a*"}]}),
                    encoding="utf-8")
    with pytest.raises(RagnarError, match="must be a list"):
        Acl.from_file(path)


