def test_markdown_sections_and_code_fences():
    md = b"# Guide\n\nGuide intro.\n\n## Install\n\n```bash\n# not a heading\ngo get x\n```\n\n## Use\n\nUsage text.\n"
    chunks = Chunker(Index(chunk_budget=30)).chunk_file("docs/guide.md", md)
    assert [c.symbol for c in chunks] == ["guide.md > Guide", "guide.md > Guide > Install", "guide.md > Guide > Use"]
    assert all(c.kind == "doc" for c in chunks)
    assert chunks[1].start_line == 5


def test_skips_generated_denied_binary_and_unknown():
    c = Chunker()
    assert c.chunk_file("x.go", b"// Code generated by protoc. DO NOT EDIT.\npackage x\n") == []
    assert c.chunk_file("vendor/lib/x.go", GO) == []
    assert c.chunk_file("img.go", bytes(10) + GO) == []
    assert c.chunk_file("logo.png", b"abc") == []
    assert Chunker(Index(max_file_kb=0)).chunk_file("x.go", GO) == []


def test_fake_embedder_is_deterministic_and_normalized():
    emb = FakeEmbedder(16)
    a, b = emb.embed_documents(["cancel order"])[0], emb.embed_query("cancel order")
    assert list(b) == a and len(a) == 16
    assert abs(sum(x * x for x in a) - 1) < 1e-9
    assert emb.embed_query("")[0] == 1.0  # never a null vector
    assert to_pgvector([0.5, -1.0]) == "[0.5,-1]"


