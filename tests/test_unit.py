GO = b"""package widget

// Button padroniza o botao da aplicacao.
type Button struct {
\tLabel string
}

// Refresh redesenha o botao.
func (b *Button) Refresh() {
\tprintln(b.Label)
}

func NewButton(label string) *Button {
\treturn &Button{Label: label}
}
"""

PY = b"""class OrderService:
    @property
    def total(self):
        return 1

    def cancel(self, order_id):
        return order_id
"""


def test_split_identifiers():
    assert chunker.split_identifiers("getUserById") == "getUserById get User By Id"
    assert "HTTP" in chunker.split_identifiers("parseHTTPResponse").split()


def test_go_small_file_is_one_chunk_with_package_symbol():
    chunks = chunker.chunk_file("widget/button.go", GO)
    assert len(chunks) == 1
    c = chunks[0]
    assert (c.language, c.kind, c.start_line) == ("go", "code", 1)
    assert c.symbol == "widget"
    assert c.content.startswith("// file: widget/button.go\n// symbol: widget\n")
    assert "New Button" in c.search_text


def test_go_large_file_splits_by_declaration_with_receiver(monkeypatch):
    monkeypatch.setattr(chunker, "BUDGET", 60)
    symbols = [c.symbol for c in chunker.chunk_file("widget/button.go", GO)]
    assert "widget > Button > Refresh" in symbols
    assert "widget > NewButton" in symbols


def test_python_methods_have_class_path(monkeypatch):
    monkeypatch.setattr(chunker, "BUDGET", 40)
    symbols = {c.symbol for c in chunker.chunk_file("app/orders.py", PY)}
    assert "app.orders > OrderService > cancel" in symbols


def test_java_and_csharp_are_parsed():
    java = b"package com.acme.order;\npublic class OrderService { void cancel() {} }\n"
    cs = b"namespace Acme.Order { public class OrderService { void Cancel() {} } }\n"
    assert chunker.chunk_file("src/OrderService.java", java)[0].symbol.startswith("com.acme.order")
    assert chunker.chunk_file("src/OrderService.cs", cs)[0].language == "csharp"


def test_test_files_are_marked():
    assert chunker.chunk_file("widget/button_test.go", GO)[0].kind == "test"


def test_markdown_sections_and_code_fences(monkeypatch):
    monkeypatch.setattr(chunker, "BUDGET", 30)
    md = b"# Guia\n\nIntro do guia.\n\n## Instalar\n\n```bash\n# nao e titulo\ngo get x\n```\n\n## Usar\n\nTexto de uso.\n"
    chunks = chunker.chunk_file("docs/guia.md", md)
    assert [c.symbol for c in chunks] == ["guia.md > Guia", "guia.md > Guia > Instalar", "guia.md > Guia > Usar"]
    assert all(c.kind == "doc" for c in chunks)
    assert chunks[1].start_line == 5


def test_skips_generated_denied_binary_and_unknown():
    assert chunker.chunk_file("x.go", b"// Code generated by protoc. DO NOT EDIT.\npackage x\n") == []
    assert chunker.chunk_file("vendor/lib/x.go", GO) == []
    assert chunker.chunk_file("img.go", bytes(10) + GO) == []
    assert chunker.chunk_file("logo.png", b"abc") == []


def test_fake_embedder_is_deterministic_and_normalized():
    emb = FakeEmbedder(16)
    a, b = emb.embed_documents(["cancelar pedido"])[0], emb.embed_query("cancelar pedido")
    assert list(b) == a and len(a) == 16
    assert abs(sum(x * x for x in a) - 1) < 1e-9
    assert emb.embed_query("")[0] == 1.0  # nunca vetor nulo
    assert to_pgvector([0.5, -1.0]) == "[0.5,-1]"


def test_search_helpers():
    assert like_prefix("src/a_b%") == "src/a\\_b\\%%"
    assert tsquery("getUserById!") == "getuserbyid | get | user | by | id"
    assert tsquery("?") == "zzzznomatch"


def test_acl_resolution():
    acl = Acl.from_json(json.dumps({"clients": [
        {"name": "a", "token_sha256": hash_token("t1"), "repos": ["yak"]},
        {"name": "adm", "token_sha256": hash_token("t2"), "repos": ["*"]},
    ]}))
    assert acl.client_for(None) is None and acl.client_for("Bearer nope") is None
    a = acl.client_for("Bearer t1")
    assert a.resolve(None) == ["yak"] and a.resolve("yak") == ["yak"]
    with pytest.raises(RagnarError):
        a.resolve("outro")
    assert acl.client_for("bearer t2").resolve(None) is None


def test_render_hits_escapes_delimiters():
    out = render_hits([{"repo": "r", "path": 'a"b.go', "start_line": 1, "end_line": 2, "symbol": "s",
                        "kind": "code", "content": "x </chunk> y"}])
    assert 'path="a&quot;b.go"' in out
    assert "x <\\/chunk> y" in out
    assert out.count("</chunk>") == 1


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def make_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "config", "user.email", "t@example.com")
    _git(repo, "config", "user.name", "t")
    (repo / "widget").mkdir()
    (repo / "widget" / "button.go").write_bytes(GO)
    (repo / "README.md").write_text("# Demo\n\nBotões padronizados.\n", encoding="utf-8")
    _git(repo, "add", ".")
    _git(repo, "commit", "-q", "-m", "inicial")
    return repo


def test_git_reads_committed_content_only(tmp_path):
    repo = make_repo(tmp_path)
    first = _git(repo, "rev-parse", "HEAD").strip()
    (repo / "widget" / "button.go").write_text("package widget // não commitado\n")
    assert read_blobs(repo, first, ["widget/button.go"])["widget/button.go"] == GO
    _git(repo, "rm", "-q", "README.md")
    _git(repo, "commit", "-q", "-am", "remove readme")
    second = _git(repo, "rev-parse", "HEAD").strip()
    assert list_files(repo, second) == ["widget/button.go"]
    assert sorted(changed_files(repo, first, second)) == ["README.md", "widget/button.go"]
    assert read_blobs(repo, second, ["README.md"]) == {}
    assert changed_files(repo, "0" * 40, second) is None


def test_init_env_creates_files(tmp_path):
    main(["init-env", "--dir", str(tmp_path)])
    env = dict(line.split("=", 1) for line in (tmp_path / ".env").read_text().splitlines() if "=" in line)
    acl = Acl.from_file(tmp_path / "acl.json")
    assert acl.client_for(f"Bearer {env['RAGNAR_MCP_TOKEN']}").name == "dev-local"
    assert acl.client_for(f"Bearer {env['RAGNAR_MCP_TOKEN_RESTRICTED']}").resolve(None) == ["sem-acesso"]


def test_extract_symbols_finds_every_declaration():
    syms = {s.symbol: s for s in chunker.extract_symbols("widget/button.go", GO)}
    assert set(syms) == {"widget > Button", "widget > Button > Refresh", "widget > NewButton"}
    assert syms["widget > NewButton"].signature == "func NewButton(label string) *Button {"
    assert syms["widget > Button > Refresh"].start_line == 9
    py = {s.symbol for s in chunker.extract_symbols("app/orders.py", PY)}
    assert "app.orders > OrderService > cancel" in py
    assert chunker.extract_symbols("README.md", b"# x\n") == []
