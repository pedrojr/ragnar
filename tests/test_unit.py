def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def make_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "config", "user.email", "t@example.com")
    _git(repo, "config", "user.name", "t")
    (repo / "widget").mkdir()
    (repo / "widget" / "button.go").write_bytes(GO)
    (repo / "README.md").write_text("# Demo\n\nStandard buttons.\n", encoding="utf-8")
    _git(repo, "add", ".")
    _git(repo, "commit", "-q", "-m", "initial")
    return repo


def test_git_reads_committed_content_only(tmp_path):
    repo = make_repo(tmp_path)
    first = _git(repo, "rev-parse", "HEAD").strip()
    (repo / "widget" / "button.go").write_text("package widget // not committed\n")
    assert read_blobs(repo, first, ["widget/button.go"])["widget/button.go"] == GO
    _git(repo, "rm", "-q", "README.md")
    _git(repo, "commit", "-q", "-am", "remove readme")
    second = _git(repo, "rev-parse", "HEAD").strip()
    assert list_files(repo, second) == ["widget/button.go"]
    assert sorted(changed_files(repo, first, second)) == ["README.md", "widget/button.go"]
    assert read_blobs(repo, second, ["README.md"]) == {}
    assert changed_files(repo, "0" * 40, second) is None


def test_init_env_creates_files(tmp_path):
    main(["init-env", "--dir", str(tmp_path)])
    env = dict(line.split("=", 1) for line in (tmp_path / ".env").read_text().splitlines() if "=" in line)
    acl = Acl.from_file(tmp_path / "acl.json")
    assert acl.client_for(f"Bearer {env['RAGNAR_MCP_TOKEN']}").name == "dev-local"
    assert acl.client_for(f"Bearer {env['RAGNAR_MCP_TOKEN_RESTRICTED']}").resolve(None) == ["no-access"]
    assert (tmp_path / "repos.toml").is_file()


def test_init_env_force_keeps_clients_added_by_hand(tmp_path, capsys):
    main(["init-env", "--dir", str(tmp_path)])
    acl_file = tmp_path / "acl.json"
    data = json.loads(acl_file.read_text(encoding="utf-8"))
    data["clients"].append({"name": "ci", "token_sha256": hash_token("ci-token"), "repos": ["app"]})
    acl_file.write_text(json.dumps(data), encoding="utf-8")
    main(["init-env", "--dir", str(tmp_path), "--force"])
    env = dict(line.split("=", 1) for line in (tmp_path / ".env").read_text().splitlines() if "=" in line)
    acl = Acl.from_file(acl_file)
    assert acl.client_for("Bearer ci-token").name == "ci"
    assert acl.client_for(f"Bearer {env['RAGNAR_MCP_TOKEN']}").name == "dev-local"
    assert [c["name"] for c in json.loads(acl_file.read_text(encoding="utf-8"))["clients"]] == \
        ["dev-local", "restricted", "ci"]


def test_init_env_with_a_broken_acl_leaves_env_alone(tmp_path):
    main(["init-env", "--dir", str(tmp_path)])
    before = (tmp_path / ".env").read_text(encoding="utf-8")
    (tmp_path / "acl.json").write_text("{not json", encoding="utf-8")
    with pytest.raises(SystemExit):
        main(["init-env", "--dir", str(tmp_path), "--force"])
    assert (tmp_path / ".env").read_text(encoding="utf-8") == before  # old tokens still match the old ACL


