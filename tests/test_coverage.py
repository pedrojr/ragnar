"""What reaches the index: large units, broken parses, oversized nodes and folder names that look like build output."""

from __future__ import annotations

import pytest

from ragnar.chunker import Chunker, cast_chunks, nws, size_index
from ragnar.config import Index
from ragnar.delphi import scan_declarations
from ragnar.embedder import FakeEmbedder
from ragnar.indexer import apply_secret_policy, content_hash, embed_all
from ragnar.languages import is_denied, is_test, language_for

CSHARP = b"""namespace Acme.Billing;

public class Invoice
{
    public int Total { get; set; }
}
"""
# `cdecl` after a method type breaks tree-sitter-pascal on real units such as HeidiSQL's dbconnection.pas
BROKEN_PASCAL = b"""unit orders;

interface

type
  TCallback = function(x: Pointer): Integer of object cdecl;
  TOrder = class(TObject)
  public
    procedure Cancel;
    function Total: Currency; stdcall;
  end;

implementation

procedure TOrder.Cancel;
begin
  Writeln('cancelled');
end;

function TOrder.Total: Currency;
begin
  Result := 0;
end;

end.
"""


@pytest.mark.parametrize("path, expected", [
    ("src/main/java/org/acme/aop/target/Pool.java", False),  # a real package in Spring
    ("spring-aop/src/main/java/org/acme/build/Plan.java", False),
    ("target/generated/Pool.java", True),
    ("module/build/generated/Foo.java", True),
    ("dist/app.js", True),
    ("pkg/build/plan.go", False),  # Go has no in-tree compiler output
    ("lcl/interfaces/win32/win32int.pp", False),  # Lazarus keeps sources in win32/
    ("source/Win32/forms.pas", False),
    ("Win32/Release/forms.pas", True),
    ("Debug/notes.pas", False),
])
def test_build_folders_only_deny_compiler_output(path, expected):
    assert is_denied(language_for(path), path) is expected


@pytest.mark.parametrize("path", ["test/Acme.Tests/Foo.cs", "src/Acme.UnitTests/Bar.cs", "src/Acme.Specs/Bar.cs",
                                  "unittests/general/foo.pas"])
def test_test_projects_are_recognized(path):
    assert is_test(language_for(path), path)


def test_small_file_names_its_namespace_and_types():
    chunk = Chunker().chunk_file("src/Invoice.cs", CSHARP)[0]
    assert chunk.symbol == "Acme.Billing > Invoice"


def test_csharp_properties_are_symbols():
    names = {s.name for s in Chunker().extract_symbols("src/Invoice.cs", CSHARP)}
    assert {"Invoice", "Total"} <= names


def test_go_constants_and_interface_methods_are_symbols():
    src = b"package x\n\nconst Limit = 3\n\ntype Store interface {\n\tGet(id int) string\n}\n\nfunc f() {\n\tconst inner = 1\n}\n"
    names = {s.name for s in Chunker().extract_symbols("x.go", src)}
    assert {"Limit", "Store", "Get", "f"} <= names and "inner" not in names


def test_large_unit_is_indexed_by_default():
    routine = "procedure Step{0};\nbegin\n  Writeln('{0}');\nend;\n\n"
    src = ("unit big;\n\ninterface\n\nimplementation\n\n" + "".join(routine.format(i) for i in range(20000)) + "end.\n").encode()
    assert len(src) > 300 * 1024
    assert Chunker().chunk_file("big.pas", src)


def test_skip_reason_names_the_cause():
    chunker = Chunker(Index(max_file_kb=1))
    assert chunker.skip_reason("big.go", b"x" * 2048) == "too large"
    assert Chunker().skip_reason("a.go", b"// Code generated by x. DO NOT EDIT.\npackage a\n") == "generated"
    assert Chunker().skip_reason("a.go", b"\x00\x01") == "binary"
    assert Chunker().skip_reason("a.go", b"package a\n") is None


def test_oversized_leaf_is_split():
    table = "\n".join(f'  "entry{i}", ' for i in range(2000))
    src = f'package x\n\nvar Table = []string{{\n{table}\n}}\n'.encode()
    chunks = Chunker().chunk_file("table.go", src)
    assert len(chunks) > 1
    assert all(nws(c.content.encode()) < 1800 * 1.5 + 200 for c in chunks)


def test_oversized_single_line_is_split_on_a_character_boundary():
    src = ('package x\n\nvar S = "' + "ç" * 5000 + '"\n').encode()
    chunks = Chunker().chunk_file("s.go", src)
    assert len(chunks) > 1
    assert not any("�" in c.content for c in chunks)


def test_size_index_matches_nws():
    src = b"a b\n\tcd  e"
    sizes = size_index(src)
    assert sizes[len(src)] == nws(src)
    assert sizes[6] - sizes[2] == nws(src[2:6])


def test_cast_chunks_accepts_a_shared_size_index():
    from tree_sitter import Parser

    from ragnar.languages import grammar_for

    src = b"package x\n\nfunc a() {}\n\nfunc b() {}\n"
    root = Parser(grammar_for(language_for("x.go"), "x.go")).parse(src).root_node
    assert cast_chunks(root, src, 5, size_index(src)) == cast_chunks(root, src, 5)


def test_scan_declarations_reads_delphi_routines_and_types():
    found = scan_declarations(BROKEN_PASCAL.decode())
    assert [(d.owners, d.name) for d in found] == [
        ((), "TOrder"), ((), "Cancel"), ((), "Total"), (("TOrder",), "Cancel"), (("TOrder",), "Total"),
    ]
    assert found[3].line == 15


def test_scan_ignores_forward_class_declarations():
    assert not scan_declarations("type\n  TOrder = class;\n  TKind = class of TOrder;\n")


def test_broken_unit_keeps_routine_boundaries_and_symbols():
    chunker = Chunker(Index(chunk_budget=40))
    chunks = chunker.chunk_file("orders.pas", BROKEN_PASCAL)
    cancel = next(c for c in chunks if "procedure TOrder.Cancel" in c.content)
    assert "Writeln('cancelled')" in cancel.content
    assert cancel.symbol.endswith("TOrder.Cancel")
    assert cancel.start_line == 15


def test_broken_unit_finds_every_routine():
    symbols = Chunker().extract_symbols("orders.pas", BROKEN_PASCAL)
    assert {"TOrder > Cancel", "TOrder > Total"} <= {s.symbol.removeprefix("orders > ") for s in symbols}


def test_embed_all_keeps_the_input_order():
    texts = ["long text " * 40, "short", "medium text " * 5]
    emb = FakeEmbedder(32)
    assert embed_all(emb, texts, "r", 2, 1) == emb.embed_documents(texts)


def test_content_hash_follows_text_and_prefix():
    assert content_hash("a", "") != content_hash("b", "")
    assert content_hash("a", "") != content_hash("a", "passage: ")


def test_secret_policy_fails_by_default():
    with pytest.raises(Exception, match=r"a\.env:3 \(aws\)"):
        apply_secret_policy({"a.env": ["3 (aws)"]}, {"a.env": b"x"}, "fail")


def test_secret_policy_skip_removes_only_those_files():
    blobs = {"a.env": b"x", "b.go": b"y"}
    assert apply_secret_policy({"a.env": ["3 (aws)"]}, blobs, "skip") == 1
    assert set(blobs) == {"b.go"}
