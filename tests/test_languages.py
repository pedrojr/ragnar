def test_generated_markers():
    assert is_generated(b"// Code generated by protoc. DO NOT EDIT.\n")
    assert is_generated(b"// <auto-generated/>\n")
    assert not is_generated(b"package x\n")


def test_settings_narrow_what_is_indexed():
    only_delphi = Chunker(languages=("delphi",))
    assert only_delphi.eligible("a.pas") and only_delphi.eligible("a.dfm") and not only_delphi.eligible("a.py")
    no_tests = Chunker(Index(index_tests=False))
    assert not no_tests.eligible("tests/a.py") and no_tests.eligible("src/a.py")
    assert not Chunker(Index(index_docs=False)).eligible("README.md")
    assert not Chunker(Index(exclude=("legacy/*",))).eligible("legacy/a.py")
    assert Chunker(Index(include=("*.vue",))).eligible("src/App.vue")


def test_sql_and_included_files_use_line_windows():
    src = "".join(f"select {i};\n" for i in range(200)).encode()
    chunks = Chunker().chunk_file("db/report.sql", src)
    assert len(chunks) > 1 and chunks[0].language == "sql"
    assert chunks[0].content.startswith("-- file: db/report.sql\n")
    assert (chunks[0].end_line, chunks[1].start_line) == (80, 71)  # overlap
    assert chunks[-1].end_line == 200
    assert Chunker(Index(include=("*.vue",))).chunk_file("App.vue", b"<template></template>\n")[0].language == "text"


def test_comment_stays_with_the_declaration_after_it():
    src = b"package a\n\n" + b"".join(
        b"// Doc%d explains the function.\nfunc F%d() int { return %d }\n\n" % (i, i, i) for i in range(6))
    chunks = Chunker(Index(chunk_budget=80)).chunk_file("a.go", src)
    bodies = [c.content for c in chunks]
    for i in range(6):
        holder = next(b for b in bodies if f"func F{i}()" in b)
        assert f"// Doc{i} explains" in holder


def test_cast_chunks_are_ordered_and_cover_the_declarations():
    from tree_sitter import Parser
    lang = language_for("a.py")
    src = b"".join(b"def f%d():\n    return %d\n\n" % (i, i) for i in range(20))
    root = Parser(grammar_for(lang, "a.py")).parse(src).root_node
    spans = cast_chunks(root, src, 40)
    assert all(a[1] <= b[0] for a, b in zip(spans, spans[1:]))
    assert all(b"def f%d" % i in src[spans[0][0] : spans[-1][1]] for i in range(20))


# Delphi legacy behavior


def test_normalize_source_handles_legacy_encodings():
    text = "// Acentuação\n"
    assert normalize_source(text.encode("cp1252")).decode() == text
    assert normalize_source(b"\xff\xfe" + text.encode("utf-16-le")).decode() == text
    assert normalize_source(b"\xfe\xff" + text.encode("utf-16-be")).decode() == text
    assert normalize_source(b"\xef\xbb\xbf" + text.encode()).decode() == text
    assert normalize_source(b"\x00\x01binary") is None


def test_utf16_delphi_source_is_indexed():
    src = "unit Pedidos;\ninterface\nimplementation\n// Situação\nend.\n"
    chunks = Chunker().chunk_file("src/Pedidos.pas", b"\xff\xfe" + src.encode("utf-16-le"))
    assert "Situação" in chunks[0].content and chunks[0].symbol.startswith("Pedidos")


FORM = """object Form1: TForm1
  Left = 0
  Top = 0
  Width = 640
  Caption = 'Customers'
  OnCreate = FormCreate
  object btnSave: TButton
    Left = 10
    Caption = 'Sa'#39've'
    OnClick = btnSaveClick
  end
  object qryCustomers: TADOQuery
    ConnectionString = 'Provider=x;Password=hidden'
    SQL.Strings = (
      'select * from customers'
      'where id = :id')
    object qryCustomersName: TStringField
      FieldName = 'NAME'
    end
  end
  object Image1: TImage
    Picture.Data = {
      0954506E67496D616765}
  end
  object lbl: TLabel
    Caption = 'long ' +
      'text'
  end
end
"""


def test_form_keeps_behavior_and_drops_geometry():
    body = Chunker().chunk_file("src/Customers.dfm", FORM.encode())[0].content
    assert "// symbol: Form1" in body
    assert "OnClick=btnSaveClick" in body and "OnCreate=FormCreate" in body
    assert "SQL=select * from customers where id = :id" in body
    assert "Caption=Sa've" in body and "Caption=long text" in body
    assert "FieldName=NAME" in body
    assert "Width" not in body and "Left" not in body and "0954506E" not in body
    assert "Password" not in body


def test_form_components_are_symbols():
    symbols = {s.symbol: s for s in Chunker().extract_symbols("src/Customers.dfm", FORM.encode())}
    assert {"Form1", "Form1 > btnSave", "Form1 > qryCustomers", "Form1 > qryCustomersName"} <= set(symbols)
    assert "OnClick=btnSaveClick" in symbols["Form1 > btnSave"].signature
    assert symbols["Form1 > btnSave"].start_line == 7


def test_inherited_forms_and_nesting():
    components = delphi.parse_form("inherited Form2: TForm2\n  inherited Panel1: TPanel\n  end\nend\n")
    assert [(c.name, c.depth, c.end_line) for c in components] == [("Form2", 0, 4), ("Panel1", 1, 3)]


def test_binary_form_is_skipped():
    assert Chunker().chunk_file("src/Old.dfm", b"TPF0\x06TForm1") == []


def test_cp1252_form_is_decoded():
    src = "object F: TForm\n  Caption = 'Situação'\nend\n".encode("cp1252")
    assert "Caption=Situação" in Chunker().chunk_file("a.dfm", src)[0].content


def test_large_form_splits_by_budget():
    body = "".join(f"  object b{i}: TButton\n    OnClick = Handler{i}\n  end\n" for i in range(60))
    chunks = Chunker(Index(chunk_budget=200)).chunk_file("a.dfm", f"object F: TForm\n{body}end\n".encode())
    assert len(chunks) > 1 and all(c.symbol == "F" for c in chunks)
    assert chunks[1].start_line > chunks[0].start_line


def test_pascal_program_with_uses_in_clause_still_chunks():
    src = b"program Hello;\nuses Forms, Unit1 in 'Unit1.pas' {Form1};\n{$R *.res}\nbegin\n  Application.Run;\nend.\n"
    chunks = Chunker().chunk_file("Hello.dpr", src)
    assert chunks and chunks[0].symbol.startswith("Hello")
