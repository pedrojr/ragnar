@pytest.mark.parametrize("name", list(CASES))
def test_language_symbols(name):
    path, src, expected = CASES[name]
    assert language_for(path).name == name
    chunks = Chunker().chunk_file(path, src)
    assert chunks and chunks[0].language == name
    assert expected <= {s.symbol for s in Chunker().extract_symbols(path, src)}


