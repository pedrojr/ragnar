"""Ragnar command line. `ragnar --help` lists the commands."""

from __future__ import annotations

import argparse
import json
import os
import secrets
import sys
from pathlib import Path

from . import __version__
from .config import CONFIG_FILE, ENV_FILE, LOCAL_CONFIG_FILE, RagnarError, load_env_file, load_settings, read_dsn, write_dsn

REPOS_TEMPLATE = """# Repositories the index worker follows. Copy the block per repository.
# [[repo]]
# name = "myapp"                                # name in the index and in the ACL
# url = "https://github.com/acme/myapp.git"
# branch = "main"
# token_env = "RAGNAR_GIT_TOKEN"                # for private repositories
# exclude = ["vendor/*"]                        # until the repository commits its own .ragnar/config.toml
"""
# Server processes never read .rag/.env: a developer's file must not hand RAGNAR_DSN_WRITE to the MCP server.
SERVER_COMMANDS = {"mcp", "embedder", "embed-preload"}


def cmd_init(args) -> None:
    from .project import init_project

    r = init_project(Path(args.dir), args.preset, args.branch, args.name, args.agents_md, args.force)
    found = ", ".join(f"{name} ({count})" for name, count in r.languages.most_common()) or "none"
    print(f"project: {r.name}, branch: {r.branch}")
    print(f"languages: {found}")
    print(f"{CONFIG_FILE}: " + ("written" if r.config_written else "kept (use --force to rewrite)"))
    for rel in (ENV_FILE, LOCAL_CONFIG_FILE):
        print(f"{rel}: " + ("written" if rel in r.local_written else "kept"))
    print(".gitignore: " + ("updated" if r.gitignore_changed else "already up to date"))
    if args.agents_md:
        print("AGENTS.md: " + ("updated" if r.agents_changed else "already up to date"))


def cmd_doctor(args) -> None:
    from .project import doctor

    checks = doctor(Path(args.dir), args.indexed_commit)
    for c in checks:
        print(f"[{c.level}] {c.name}" + (f": {c.detail}" if c.detail else ""))
    sys.exit(1 if any(c.level == "fail" for c in checks) else 0)


def cmd_init_env(args) -> None:
    """Creates .env (random passwords and tokens), acl.json and repos.toml, if they do not exist."""
    root = Path(args.dir)
    env_file, acl_file, repos_file = root / ".env", root / "acl.json", root / "repos.toml"
    if env_file.exists() and not args.force:
        print(f"{env_file} already exists (use --force to recreate)")
        return
    from .acl import hash_token, new_token

    token, restricted = new_token(), new_token()
    values = {
        "POSTGRES_PASSWORD": secrets.token_hex(16),
        "REPLICATION_PASSWORD": secrets.token_hex(16),
        "RAGNAR_WRITER_PASSWORD": secrets.token_hex(16),
        "RAGNAR_READER_PASSWORD": secrets.token_hex(16),
        "RAGNAR_MCP_TOKEN": token,
        "RAGNAR_MCP_TOKEN_RESTRICTED": restricted,
        "RAGNAR__EMBEDDING__MODEL": "jinaai/jina-embeddings-v2-base-code",
        "RAGNAR__EMBEDDING__DIM": "768",
    }
    env_file.write_text("# Generated by `ragnar init-env`. Never commit this file.\n"
                        + "".join(f"{k}={v}\n" for k, v in values.items()), encoding="utf-8")
    acl = {"clients": [
        {"name": "dev-local", "token_sha256": hash_token(token), "repos": ["*"]},
        {"name": "restricted", "token_sha256": hash_token(restricted), "repos": ["no-access"]},
    ]}
    acl_file.write_text(json.dumps(acl, indent=2) + "\n", encoding="utf-8")
    if not repos_file.exists():
        repos_file.write_text(REPOS_TEMPLATE, encoding="utf-8")
    print(f"created {env_file}, {acl_file} and {repos_file}")


def cmd_token(args) -> None:
    from .acl import hash_token, new_token

    token = new_token()
    print(f"token (hand it to the client, do not store it): {token}")
    print("entry for acl.json:")
    print(json.dumps({"name": args.name, "token_sha256": hash_token(token), "repos": args.repos.split(",")}))


def cmd_migrate(args) -> None:
    from .migrate import migrate, resize_embeddings

    applied = migrate(write_dsn())
    print("migrations applied: " + (", ".join(applied) if applied else "none pending"))
    if args.resize_embeddings:
        print(f"index cleared, embedding dimension is now {resize_embeddings(write_dsn())}: index every repository again")


def cmd_index(args) -> None:
    from .embedder import from_settings
    from .indexer import index

    if args.no_secret_scan:
        print("WARNING: secret scan is off", file=sys.stderr)
    settings = load_settings(overrides=args.set)
    r = index(args.source, args.repo, write_dsn(), from_settings(settings), settings, ref=args.ref, full=args.full,
              scan=not args.no_secret_scan)
    print(f"{r.repo}: {r.mode} at {r.commit_sha[:12]}: {r.files} files, {r.chunks} chunks written, "
          f"{r.deleted_chunks} removed, {r.reused_vectors} vectors reused, {r.seconds}s")
    if r.skipped:
        print("left out: " + ", ".join(f"{n} {reason}" for reason, n in sorted(r.skipped.items())))


def cmd_sync(args) -> None:
    from .embedder import from_settings
    from .sync import load_repos, sync_once, watch

    settings = load_settings(overrides=args.set)
    repos = load_repos(args.config)
    if args.repo:
        repos = [r for r in repos if r.name == args.repo]
    if not repos:
        print(f"no repository to sync in {args.config}", file=sys.stderr)
    emb = from_settings(settings)
    if args.watch:
        watch(lambda: load_repos(args.config), write_dsn(), emb, settings, args.interval)
        return
    _, errors = sync_once(repos, write_dsn(), emb, settings)
    sys.exit(1 if errors else 0)


def cmd_search(args) -> None:
    import psycopg

    from .embedder import from_settings
    from .llm import chat_from, reranker_from
    from .mcp_server import render_hits
    from .search import Pipeline

    settings = load_settings(overrides=args.set)
    pipeline = Pipeline(settings, from_settings(settings), chat_from(settings), reranker_from(settings))
    with psycopg.connect(read_dsn()) as conn:
        hits, timing = pipeline.search(conn, [args.repo], args.query, args.k, args.path_prefix)
    print(render_hits(hits))
    print(", ".join(f"{phase} {seconds * 1000:.0f} ms" for phase, seconds in timing.items()), file=sys.stderr)


def cmd_summarize(args) -> None:
    """Previews file summaries with the configured model. Reads local files and writes nothing."""
    from .config import matches_path, summary_settings
    from .llm import Chat, summarize

    settings = load_settings(overrides=args.set)
    model = summary_settings(settings)
    if not (model.url and model.model):
        raise RagnarError("no summary model: set summaries.provider (ollama | anthropic), "
                          "or summaries.url and summaries.model, or the same keys in [llm]")
    print(f"provider: {model.provider}, model: {model.model}, url: {model.url}", file=sys.stderr)
    excluded = settings.summaries.exclude + settings.index.summary_exclude
    files = []
    for name in args.files:
        path = Path(name)
        rel = path.as_posix().removeprefix("./")
        if matches_path(excluded, rel):
            print(f"{rel}: excluded by summaries.exclude or index.summary_exclude (summarized anyway)", file=sys.stderr)
        raw = path.read_bytes()
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            text = raw.decode(settings.index.legacy_encoding, errors="replace")
        files.append({"path": rel, "text": text, "declarations": "", "refers": ""})
    for f, summary in zip(files, summarize(Chat(model), settings.summaries, files)):
        print(f"## {f['path']}\n{summary}\n")


def cmd_eval_golden(args) -> None:
    from .evaluation import build_golden

    golden = build_golden(args.repo, args.snapshot, args.branch)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("".join(json.dumps(q, ensure_ascii=False) + "\n" for q in golden), encoding="utf-8")
    print(f"{len(golden)} questions written to {args.out}")


def cmd_eval_run(args) -> None:
    from .evaluation import compare, format_report, read_golden

    golden = read_golden(args.golden)
    if not golden:
        raise RagnarError("empty golden set: no eligible commits after the snapshot")
    variants = {}
    for item in args.variant:
        name, sep, changes = item.partition(":")
        if not sep:
            raise RagnarError(f"expected name:section.key=value[,section.key=value], got {item!r}")
        variants[name] = changes.split(",")
    report = compare(read_dsn(), args.repo, args.snapshot, args.index_name, golden, variants, args.set)
    print(format_report(report))
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


def cmd_mcp(args) -> None:
    import uvicorn

    uvicorn.run("ragnar.mcp_server:build_app", factory=True, host=args.host, port=args.port,
                log_level="warning", access_log=False)


def cmd_embedder(args) -> None:
    import uvicorn

    uvicorn.run("ragnar.embed_server:build_app", factory=True, host=args.host, port=args.port,
                log_level="warning", access_log=False)


def cmd_embed_preload(_args) -> None:
    from .embed_server import preload

    preload()


def cmd_smoke(args) -> None:
    from .ops import smoke

    ok = smoke(args.url, os.environ["RAGNAR_MCP_TOKEN"], os.environ.get("RAGNAR_MCP_TOKEN_RESTRICTED"), args.repo,
               os.environ.get("RAGNAR_DSN_WRITE"), os.environ.get("RAGNAR_DSN_READ"), args.replica_host)
    sys.exit(0 if ok else 1)


def cmd_load(args) -> None:
    from .ops import load

    queries = Path(args.queries).read_text(encoding="utf-8").splitlines() if args.queries else None
    load(args.url, os.environ["RAGNAR_MCP_TOKEN"], args.concurrency, args.duration, queries, args.rate)


def cmd_stats(args) -> None:
    from .stats import labels, parse, report

    lines = sys.stdin if args.log == "-" else Path(args.log).read_text(encoding="utf-8", errors="replace").splitlines()
    events = parse(lines)
    if args.labels:
        found = labels(events)
        Path(args.labels).write_text("".join(json.dumps(q, ensure_ascii=False) + "\n" for q in found), encoding="utf-8")
        print(f"{len(found)} questions written to {args.labels}", file=sys.stderr)
    print(json.dumps(report(events), indent=1, ensure_ascii=False))


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="ragnar", description=__doc__)
    p.add_argument("--version", action="version", version=f"ragnar {__version__}")
    sub = p.add_subparsers(dest="cmd", required=True)

    def with_overrides(s: argparse.ArgumentParser) -> None:
        s.add_argument("--set", action="append", default=[], metavar="SECTION.KEY=VALUE",
                       help="overrides one setting for this run; repeatable")

    s = sub.add_parser("init", help="ragnarizes a project: .ragnar/, .rag/ and .gitignore")
    s.add_argument("--dir", default=".")
    s.add_argument("--preset", default="balanced", help="economy, balanced or precise")
    s.add_argument("--branch", help="branch the index follows (default: the repository's default branch)")
    s.add_argument("--name", help="repository name in the index (default: folder name)")
    s.add_argument("--agents-md", action="store_true", help="adds a search note to AGENTS.md")
    s.add_argument("--force", action="store_true", help="rewrites an existing .ragnar/config.toml")
    s.set_defaults(fn=cmd_init)

    s = sub.add_parser("stats", help="usage report from the MCP server's audit lines")
    s.add_argument("log", help="file with the server's stdout, or - for stdin")
    s.add_argument("--labels", help="writes questions answered by a later read_code, for ragnar eval run")
    s.set_defaults(fn=cmd_stats)

    s = sub.add_parser("doctor", help="checks the health of a ragnarized project")
    s.add_argument("--dir", default=".")
    s.add_argument("--indexed-commit", help="commit reported by list_repos, to measure how far behind the index is")
    s.set_defaults(fn=cmd_doctor)

    s = sub.add_parser("init-env", help="creates .env, acl.json and repos.toml for the example infrastructure")
    s.add_argument("--dir", default=".")
    s.add_argument("--force", action="store_true")
    s.set_defaults(fn=cmd_init_env)

    s = sub.add_parser("token", help="creates a token and its ACL entry")
    s.add_argument("--name", required=True)
    s.add_argument("--repos", required=True, help="comma-separated list; * allows all")
    s.set_defaults(fn=cmd_token)

    s = sub.add_parser("migrate", help="applies migrations on the primary (RAGNAR_DSN_WRITE)")
    s.add_argument("--resize-embeddings", action="store_true",
                   help="CLEARS the index and applies embedding.dim, after a model change")
    s.set_defaults(fn=cmd_migrate)

    s = sub.add_parser("index", help="initial build or increment of a repository (RAGNAR_DSN_WRITE)")
    s.add_argument("source", help="local path or git URL")
    s.add_argument("repo", help="repository name in the index")
    s.add_argument("--ref", help="branch or commit (default: project.branch)")
    s.add_argument("--full", action="store_true", help="reindexes everything")
    s.add_argument("--no-secret-scan", action="store_true", help="for tests only: skips gitleaks")
    with_overrides(s)
    s.set_defaults(fn=cmd_index)

    s = sub.add_parser("sync", help="indexes the branches listed in repos.toml (RAGNAR_DSN_WRITE)")
    s.add_argument("--config", default="repos.toml")
    s.add_argument("--repo", help="only this repository")
    s.add_argument("--watch", action="store_true", help="keeps polling")
    s.add_argument("--interval", type=float, default=60, help="seconds between passes with --watch")
    with_overrides(s)
    s.set_defaults(fn=cmd_sync)

    s = sub.add_parser("search", help="direct search on the read database, for debugging")
    s.add_argument("query")
    s.add_argument("--repo", required=True)
    s.add_argument("-k", type=int)
    s.add_argument("--path-prefix", default="")
    with_overrides(s)
    s.set_defaults(fn=cmd_search)

    s = sub.add_parser("summarize", help="previews file summaries with the configured model; writes nothing")
    s.add_argument("files", nargs="+", help="local files, paths relative to the repository root")
    with_overrides(s)
    s.set_defaults(fn=cmd_summarize)

    evaluation = sub.add_parser("eval", help="measures retrieval against the git history")
    evaluation = evaluation.add_subparsers(dest="eval_cmd", required=True)
    s = evaluation.add_parser("golden", help="builds questions from the commits after a snapshot")
    s.add_argument("repo", help="local repository path")
    s.add_argument("snapshot", help="commit the snapshot index was built from")
    s.add_argument("--branch", default="main")
    s.add_argument("--out", default=".ragnar/eval/golden.jsonl")
    s.set_defaults(fn=cmd_eval_golden)
    s = evaluation.add_parser("run", help="compares grep, the configuration and its variants (RAGNAR_DSN_READ)")
    s.add_argument("repo", help="local repository path")
    s.add_argument("snapshot")
    s.add_argument("index_name", help="name of the snapshot in the index")
    s.add_argument("--golden", default=".ragnar/eval/golden.jsonl")
    s.add_argument("--variant", action="append", default=[], metavar="NAME:SECTION.KEY=VALUE[,...]",
                   help="another configuration to score; repeatable")
    s.add_argument("--out", default=".rag/eval/report.json", help="writes the report as JSON")
    with_overrides(s)
    s.set_defaults(fn=cmd_eval_run)

    for name, fn, port in (("mcp", cmd_mcp, 8080), ("embedder", cmd_embedder, 8000)):
        s = sub.add_parser(name, help=f"runs the {name} HTTP server")
        s.add_argument("--host", default="0.0.0.0")
        s.add_argument("--port", type=int, default=port)
        s.set_defaults(fn=fn)

    sub.add_parser("embed-preload", help="downloads the embedding model (image build)").set_defaults(fn=cmd_embed_preload)

    s = sub.add_parser("smoke", help="end-to-end check through MCP, plus the write barriers")
    s.add_argument("--url", default="http://127.0.0.1:8080/mcp")
    s.add_argument("--repo", required=True)
    s.add_argument("--replica-host", help="a replica host, to test that it refuses writes")
    s.set_defaults(fn=cmd_smoke)

    s = sub.add_parser("load", help="search load through MCP")
    s.add_argument("--url", default="http://127.0.0.1:8080/mcp")
    s.add_argument("--concurrency", type=int, default=8)
    s.add_argument("--duration", type=float, default=120)
    s.add_argument("--rate", type=float, default=0, help="total searches/s (0 = as fast as possible)")
    s.add_argument("--queries", help="file with one query per line")
    s.set_defaults(fn=cmd_load)

    args = p.parse_args(argv)
    if args.cmd not in SERVER_COMMANDS:
        load_env_file()
    try:
        args.fn(args)
    except RagnarError as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
