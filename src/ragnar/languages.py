BY_NAME = {lang.name: lang for lang in LANGUAGES}
BY_EXTENSION = {ext: lang for lang in LANGUAGES for ext in lang.extensions}
DOC_EXTENSIONS = (".md", ".mdx")
FORM_EXTENSIONS = (".dfm", ".fmx", ".lfm")  # Delphi and Lazarus forms, parsed by ragnar.delphi


def language_for(path: str) -> Language | None:
    return BY_EXTENSION.get(PurePosixPath(path).suffix.lower())


@cache
def _load(module: str, function: str) -> TSLanguage:
    return TSLanguage(getattr(importlib.import_module(module), function)())


def grammar_for(lang: Language, path: str) -> TSLanguage | None:
    grammar = lang.grammars.get(PurePosixPath(path).suffix.lower(), lang.grammar)
    return _load(*grammar) if grammar else None


def is_test(lang: Language | None, path: str) -> bool:
    if COMMON_TESTS.search(path):
        return True
    return bool(lang and lang.tests and lang.tests.search(path))


def is_denied(lang: Language | None, path: str) -> bool:
    if COMMON_DENY.search(path):
        return True
    if lang is None or lang.build_output:
        # org/acme/target/Pool.java is a package. Only a folder outside the source root is compiler output.
        match = BUILD_OUTPUT.search(path)
        root = SOURCE_ROOT.search(path)
        if match and not (root and root.start() <= match.start()):
            return True
    return bool(lang and lang.deny and lang.deny.search(path))


def is_generated(src: bytes) -> bool:
    return bool(GENERATED.search(src[:2000]))
