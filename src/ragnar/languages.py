"""Language registry: what each language needs for good chunks and symbols.

A profile declares the extensions, the tree-sitter grammar, the AST nodes that define a
symbol, how to spot tests, and what to skip. Adding a language means adding a profile
here and a test in tests/test_languages.py.
"""

from __future__ import annotations

import importlib
import re
from collections.abc import Callable
from dataclasses import dataclass, field
from functools import cache
from pathlib import PurePosixPath

from tree_sitter import Language as TSLanguage
