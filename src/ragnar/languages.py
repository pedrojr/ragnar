IDENTIFIERS = {"identifier", "type_identifier", "simple_identifier", "field_identifier", "constant",
               "word", "property_identifier", "name", "namespace_identifier"}
COMMON_TESTS = re.compile(r"(^|/)(tests?|specs?|__tests__|testing|unittests?)/|(^|/)[^/]+\.(Unit|Integration)?(Tests?|Specs)/")
COMMON_DENY = re.compile(
    r"(^|/)(vendor|node_modules|third_party|__pycache__|\.venv|venv|\.git|\.ragnar|migrations/snapshots)/"
    r"|\.min\.(js|css)$"
)
BUILD_OUTPUT = re.compile(r"(^|/)(bin|obj|target|build|dist|out)/")  # real packages have these names too, see is_denied
SOURCE_ROOT = re.compile(r"(^|/)(src|source|sources)/")
GENERATED = re.compile(rb"Code generated .* DO NOT EDIT|<auto-generated|@generated|automatically generated", re.I)


def text_of(node: Node | None) -> str:
    return node.text.decode(errors="replace") if node is not None and node.text is not None else ""


def default_name(node: Node) -> tuple[list[str], str]:
    """(owners, name) of a declaration. The default reads the `name` field or the first identifier."""
    named = node.child_by_field_name("name")
    if named is None:
        named = next((c for c in node.children if c.type in IDENTIFIERS), None)
    return [], text_of(named)


def _go_name(node: Node) -> tuple[list[str], str]:
    owners, name = default_name(node)
    stack = [node.child_by_field_name("receiver")] if node.type == "method_declaration" else []
    while stack:
        n = stack.pop(0)
        if n is None:
            continue
        if n.type == "type_identifier":
            return [text_of(n)], name
        stack.extend(n.children)
    return owners, name


def _c_name(node: Node) -> tuple[list[str], str]:
    if node.child_by_field_name("name") is not None:
        return default_name(node)
    n = node.child_by_field_name("declarator")
    while n is not None and n.child_by_field_name("declarator") is not None:
        n = n.child_by_field_name("declarator")
    if n is None:
        return [], ""
    if n.type == "qualified_identifier":
        parts = re.split(r"::", text_of(n))
        return parts[:-1], parts[-1]
    return [], text_of(n)


def _rust_name(node: Node) -> tuple[list[str], str]:
    if node.type == "impl_item":
        return [], re.sub(r"<.*", "", text_of(node.child_by_field_name("type")))
    return default_name(node)


def _pascal_name(node: Node) -> tuple[list[str], str]:
    head = next((c for c in node.children if c.type == "declProc"), node) if node.type == "defProc" else node
    dotted = next((c for c in head.children if c.type == "genericDot"), None)
    if dotted is not None:
        parts = [text_of(c) for c in dotted.children if c.type == "identifier"]
        return parts[:-1], parts[-1] if parts else ""
    return default_name(head)


def _csharp_module(root: Node, _: str) -> str:
    for child in root.children:
        if child.type == "file_scoped_namespace_declaration":
            return text_of(child.child_by_field_name("name"))
    return ""


def _accept_all(_: Node) -> bool:
    return True


def _accept_js(node: Node) -> bool:
    if node.type != "variable_declarator":
        return True
    value = node.child_by_field_name("value")
    return value is not None and value.type in ("arrow_function", "function_expression", "class")


def _accept_c(node: Node) -> bool:
    return node.type == "function_definition" or node.child_by_field_name("body") is not None


def _accept_go(node: Node) -> bool:
    if node.type not in ("const_spec", "var_spec"):
        return True
    return node.parent is not None and node.parent.parent is not None and node.parent.parent.type == "source_file"


def _accept_pascal(node: Node) -> bool:
    return node.type != "declProc" or (node.parent is not None and node.parent.type != "defProc")


def _no_module(_: Node, __: str) -> str:
    return ""


def _python_module(_: Node, path: str) -> str:
    return ".".join(PurePosixPath(path).with_suffix("").parts)


def _child_module(kind: str, strip: str = "") -> Callable[[Node, str], str]:
    def module(root: Node, _: str) -> str:
        for child in root.children:
            if child.type == kind:
                named = child.child_by_field_name("name")
                value = text_of(named) if named is not None else text_of(child)
                return value.removeprefix(strip).strip(" ;\t\r\n")
        return ""
    return module


def _go_module(root: Node, _: str) -> str:
    for child in root.children:
        if child.type == "package_clause":
            return next((text_of(c) for c in child.children if c.type == "package_identifier"), "")
    return ""


def _pascal_module(root: Node, _: str) -> str:
    for child in root.children:
        name = next((c for c in child.children if c.type == "moduleName"), None)
        if name is not None:
            return text_of(name)
    return ""


@dataclass(frozen=True)
class Language:
    name: str
    extensions: tuple[str, ...]
    grammar: tuple[str, str] | None = None  # (module, function); None uses the line-window chunker
    declarations: frozenset[str] = frozenset()
    scopes: frozenset[str] = frozenset()  # name the symbol path, but are not symbols themselves
    comment: str = "//"
    tests: re.Pattern | None = None
    deny: re.Pattern | None = None
    name_of: Callable[[Node], tuple[list[str], str]] = default_name
    accept: Callable[[Node], bool] = _accept_all
    module_of: Callable[[Node, str], str] = _no_module
    grammars: dict[str, tuple[str, str]] = field(default_factory=dict)  # extension -> grammar, when it differs
    build_output: bool = True  # bin/, build/, target/ hold compiler output, not sources
    fallback: Callable[[str], list[Declaration]] | None = None  # declarations of a file the grammar cannot parse


def _nodes(*names: str) -> frozenset[str]:
    return frozenset(names)


