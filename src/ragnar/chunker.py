"""Chunking por AST (cAST) com tree-sitter para Java, C#, Go e Python, e por seção para Markdown.

Algoritmo da seção 3.1 do guia: nó que cabe no orçamento vira chunk; senão divide
nos filhos e junta vizinhos enquanto couberem. Tamanho medido em caracteres sem espaço.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import PurePosixPath

import tree_sitter_c_sharp
import tree_sitter_go
import tree_sitter_java
import tree_sitter_python
from tree_sitter import Language, Node, Parser

LANGS = {
    ".java": ("java", Language(tree_sitter_java.language())),
    ".cs": ("csharp", Language(tree_sitter_c_sharp.language())),
    ".go": ("go", Language(tree_sitter_go.language())),
    ".py": ("python", Language(tree_sitter_python.language())),
}
DOC_SUFFIXES = {".md"}
DECL_TYPES = {
    "class_declaration", "interface_declaration", "enum_declaration", "record_declaration",
    "struct_declaration", "method_declaration", "constructor_declaration",
    "namespace_declaration", "file_scoped_namespace_declaration",
    "function_declaration", "class_definition", "function_definition", "type_spec",
}
DENY = re.compile(
    r"(^|/)(vendor|node_modules|bin|obj|target|build|dist|__pycache__|\.venv|migrations/snapshots)/"
    r"|\.(min\.js|pb\.go|g\.cs|designer\.cs)$|_pb2\.py$"
)
GENERATED = re.compile(rb"Code generated .* DO NOT EDIT|<auto-generated", re.I)
TEST_PATH = re.compile(r"(^|/)(tests?|spec)/|Tests?\.(java|cs)$|_test\.(go|py)$|(^|/)test_[^/]*\.py$")
BUDGET = 1800  # caracteres sem espaço por chunk
MAX_FILE_BYTES = 300_000


@dataclass(frozen=True)
class Chunk:
    path: str
    symbol: str
    language: str
    kind: str  # code | test | doc
    start_line: int
    end_line: int
    content: str  # cabeçalho + trecho
    search_text: str  # content + identificadores separados (BM25)


def eligible(path: str) -> bool:
    suffix = PurePosixPath(path).suffix
    return (suffix in LANGS or suffix in DOC_SUFFIXES) and not DENY.search(path)


def nws(b: bytes) -> int:
    return len(re.sub(rb"\s", b"", b))


def split_identifiers(text: str) -> str:
    """getUserById -> 'getUserById get User By Id' para a busca lexical."""
    out = []
    for w in re.findall(r"[A-Za-z][A-Za-z0-9]*", text):
        out.append(w)
        out += re.findall(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+", w)
    return " ".join(out)


def cast_chunks(node: Node, src: bytes) -> list[tuple[int, int]]:
    if nws(src[node.start_byte : node.end_byte]) <= BUDGET or not node.children:
        return [(node.start_byte, node.end_byte)]
    spans: list[tuple[int, int]] = []
    cur: tuple[int, int] | None = None
    for child in node.children:
        for s, e in cast_chunks(child, src):
            if cur and nws(src[cur[0] : e]) <= BUDGET:
                cur = (cur[0], e)
            else:
                if cur:
                    spans.append(cur)
                cur = (s, e)
    if cur:
        spans.append(cur)
    return spans


def _text(node: Node | None) -> str:
    return node.text.decode(errors="replace") if node is not None and node.text is not None else ""


def module_name(root: Node, path: str, lang: str) -> str:
    """Pacote ou namespace do arquivo, para o símbolo."""
    for child in root.children:
        if lang == "go" and child.type == "package_clause":
            return next((_text(c) for c in child.children if c.type == "package_identifier"), "")
        if lang == "java" and child.type == "package_declaration":
            return _text(child).removeprefix("package").strip(" ;")
    if lang == "python":
        return ".".join(PurePosixPath(path).with_suffix("").parts)
    return ""


def go_receiver(node: Node) -> str:
    recv = node.child_by_field_name("receiver")
    stack = [recv] if recv is not None else []
    while stack:
        n = stack.pop(0)
        if n.type == "type_identifier":
            return _text(n)
        stack.extend(n.children)
    return ""


def enclosing_symbol(root: Node, s: int, e: int, lang: str) -> str:
    names, n = [], root.named_descendant_for_byte_range(s, max(s, e - 1))
    while n is not None:
        if n.type in DECL_TYPES and (name := n.child_by_field_name("name")) is not None:
            names.append(_text(name))
            if lang == "go" and n.type == "method_declaration" and (recv := go_receiver(n)):
                names.append(recv)
        n = n.parent
    return " > ".join(reversed(names))


def _make(path: str, symbol: str, language: str, kind: str, start: int, end: int, text: str) -> Chunk:
    header = f"// file: {path}\n// symbol: {symbol}\n"
    content = header + text
    return Chunk(path, symbol, language, kind, start, end, content, content + "\n" + split_identifiers(content))


def chunk_code(path: str, src: bytes) -> list[Chunk]:
    lang_name, lang = LANGS[PurePosixPath(path).suffix]
    root = Parser(lang).parse(src).root_node
    kind = "test" if TEST_PATH.search(path) else "code"
    module = module_name(root, path, lang_name)
    out = []
    for s, e in cast_chunks(root, src):
        text = src[s:e].decode(errors="replace")
        if not text.strip():
            continue
        symbol = " > ".join(p for p in (module, enclosing_symbol(root, s, e, lang_name)) if p)
        start, end = src[:s].count(b"\n") + 1, src[:e].count(b"\n") + 1
        out.append(_make(path, symbol, lang_name, kind, start, end, text))
    return out


HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*#*\s*$")


def chunk_markdown(path: str, src: bytes) -> list[Chunk]:
    """Uma seção por título; seções pequenas vizinhas se juntam até o orçamento."""
    lines = src.decode(errors="replace").splitlines(keepends=True)
    sections: list[tuple[str, int, int]] = []  # (trilha de títulos, linha inicial, linha final)
    trail: list[tuple[int, str]] = []
    start, fence = 1, False
    for i, line in enumerate(lines, 1):
        if line.lstrip().startswith(("```", "~~~")):
            fence = not fence
        m = None if fence else HEADING.match(line)
        if m and i > start:
            sections.append((" > ".join(t for _, t in trail), start, i - 1))
            start = i
        if m:
            level = len(m.group(1))
            trail = [(lv, t) for lv, t in trail if lv < level] + [(level, m.group(2))]
    sections.append((" > ".join(t for _, t in trail), start, len(lines)))

    out, cur = [], None
    for title, s, e in sections:
        if cur and nws("".join(lines[cur[1] - 1 : e]).encode()) <= BUDGET:
            cur = (cur[0], cur[1], e)
            continue
        if cur:
            out.append(cur)
        cur = (title, s, e)
    if cur:
        out.append(cur)

    doc = PurePosixPath(path).name
    chunks = []
    for title, s, e in out:
        text = "".join(lines[s - 1 : e])
        if text.strip():
            symbol = f"{doc} > {title}" if title else doc
            chunks.append(_make(path, symbol, "markdown", "doc", s, e, text))
    return chunks


def chunk_file(path: str, src: bytes) -> list[Chunk]:
    """Chunks do arquivo, ou lista vazia se ele não deve ser indexado."""
    if not eligible(path) or len(src) > MAX_FILE_BYTES or is_binary(src) or GENERATED.search(src[:2000]):
        return []
    if PurePosixPath(path).suffix in DOC_SUFFIXES:
        return chunk_markdown(path, src)
    return chunk_code(path, src)


def is_binary(src: bytes) -> bool:
    return bytes(1) in src[:8000]  # NUL nos primeiros 8 KB


@dataclass(frozen=True)
class Symbol:
    path: str
    symbol: str  # nome qualificado: pacote > tipo > método
    name: str
    node_type: str
    kind: str
    start_line: int
    end_line: int
    signature: str  # primeira linha da declaração


def extract_symbols(path: str, src: bytes) -> list[Symbol]:
    """Todas as declarações com nome (classe, tipo, função, método), mesmo as que dividem chunk com outras."""
    if not eligible(path) or PurePosixPath(path).suffix not in LANGS or len(src) > MAX_FILE_BYTES \
            or is_binary(src) or GENERATED.search(src[:2000]):
        return []
    lang_name, lang = LANGS[PurePosixPath(path).suffix]
    root = Parser(lang).parse(src).root_node
    kind = "test" if TEST_PATH.search(path) else "code"
    module = module_name(root, path, lang_name)
    out: list[Symbol] = []

    def walk(node: Node, trail: list[str]) -> None:
        for child in node.children:
            name_node = child.child_by_field_name("name") if child.type in DECL_TYPES else None
            if name_node is None:
                walk(child, trail)
                continue
            name = _text(name_node)
            owner = [go_receiver(child)] if lang_name == "go" and child.type == "method_declaration" else []
            parts = [p for p in [module, *trail, *owner, name] if p]
            signature = _text(child).splitlines()[0].strip() if child.text else ""
            out.append(Symbol(path, " > ".join(parts), name, child.type, kind,
                              child.start_point[0] + 1, child.end_point[0] + 1, signature[:200]))
            walk(child, [*trail, *owner, name])

    walk(root, [])
    return out
